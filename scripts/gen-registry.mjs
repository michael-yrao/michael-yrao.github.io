// Generates src/app/core/data/algorithms.index.ts from the *.steps.ts files' AST.
// Default: write the file. `--check`: write nothing, exit 1 when the committed file is stale.
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import prettier from 'prettier';
import ts from 'typescript';

const REPO_ROOT = fileURLToPath(new URL('../', import.meta.url));
const ALGORITHMS_DIR = join(REPO_ROOT, 'src/app/algorithms');
const MODEL_FILE = join(REPO_ROOT, 'src/app/core/models/algorithm.model.ts');
const OUTPUT_FILE = join(REPO_ROOT, 'src/app/core/data/algorithms.index.ts');
const STEPS_SUFFIX = '.steps.ts';
const META_SUFFIX = 'Meta';
const CATEGORY_LABELS_NAME = 'CATEGORY_LABELS';
const CHECK_FLAG = '--check';
const LITERAL_FIELDS = ['id', 'lcNumber', 'title', 'difficulty', 'category', 'hint'];

const HEADER = '// GENERATED by scripts/gen-registry.mjs — do not edit';

const PREAMBLE = `
import type { AlgorithmMeta, Category, Difficulty } from '../models/algorithm.model';

export interface AlgorithmIndexEntry {
  readonly id: string;
  readonly lcNumber: number;
  readonly title: string;
  readonly difficulty: Difficulty;
  readonly category: Category;
  readonly tags: readonly string[];
  readonly hint: string;
  readonly hasVisualization: boolean;
  readonly variants: readonly { readonly variant: string; readonly label: string }[];
  readonly load: () => Promise<AlgorithmMeta>;
}

function once<T>(fn: () => Promise<T>): () => Promise<T> {
  let cached: Promise<T> | undefined;
  return () => (cached ??= fn());
}
`;

const POSTAMBLE = `
let allAlgorithms: Promise<AlgorithmMeta[]> | undefined;

export function loadAllAlgorithms(): Promise<AlgorithmMeta[]> {
  allAlgorithms ??= Promise.all(ALGORITHM_INDEX.map((entry) => entry.load()));
  return allAlgorithms;
}
`;

function parse(file) {
  return ts.createSourceFile(file, readFileSync(file, 'utf8'), ts.ScriptTarget.Latest, true);
}

function where(node) {
  const sf = node.getSourceFile();
  return `${sf.fileName}:${sf.getLineAndCharacterOfPosition(node.getStart(sf)).line + 1}`;
}

function fail(node, message) {
  throw new Error(`${where(node)}: ${message}`);
}

function propertyName(prop) {
  return prop.name && (ts.isIdentifier(prop.name) || ts.isStringLiteral(prop.name))
    ? prop.name.text
    : undefined;
}

/** The value node of `name`; a shorthand `{ name }` yields its identifier. */
function getProp(objectLiteral, name) {
  const prop = objectLiteral.properties.find(
    (p) =>
      (ts.isPropertyAssignment(p) || ts.isShorthandPropertyAssignment(p)) &&
      propertyName(p) === name,
  );
  if (!prop) fail(objectLiteral, `missing property '${name}'`);
  return ts.isShorthandPropertyAssignment(prop) ? prop.name : prop.initializer;
}

/** An object literal, or an identifier naming a top-level `const x = { ... }` in the same file. */
function resolveObjectLiteral(node) {
  if (ts.isObjectLiteralExpression(node)) return node;
  if (!ts.isIdentifier(node)) return fail(node, 'solution must be an object literal or a const');
  for (const stmt of node.getSourceFile().statements) {
    if (!ts.isVariableStatement(stmt)) continue;
    for (const decl of stmt.declarationList.declarations) {
      const isMatch = ts.isIdentifier(decl.name) && decl.name.text === node.text;
      if (isMatch && decl.initializer && ts.isObjectLiteralExpression(decl.initializer)) {
        return decl.initializer;
      }
    }
  }
  return fail(node, `'${node.text}' is not a top-level const object literal`);
}

function literalValue(node, name) {
  if (ts.isStringLiteral(node) || ts.isNoSubstitutionTemplateLiteral(node)) return node.text;
  if (ts.isNumericLiteral(node)) return Number(node.text);
  return fail(node, `'${name}' must be a plain string or number literal`);
}

function stringArray(node, name) {
  if (!ts.isArrayLiteralExpression(node)) fail(node, `'${name}' must be an array literal`);
  return node.elements.map((el) => literalValue(el, name));
}

/** `() => []`: an arrow function with no parameters whose body is an empty array literal. */
function isEmptyStepsStub(node) {
  return (
    ts.isArrowFunction(node) &&
    node.parameters.length === 0 &&
    ts.isArrayLiteralExpression(node.body) &&
    node.body.elements.length === 0
  );
}

function readSolution(element) {
  const node = resolveObjectLiteral(element);
  return {
    label: literalValue(getProp(node, 'label'), 'label'),
    variant: literalValue(getProp(node, 'variant'), 'variant'),
    isStub: isEmptyStepsStub(getProp(node, 'generateSteps')),
  };
}

function findMetaDeclaration(sf) {
  const found = [];
  for (const stmt of sf.statements) {
    if (!ts.isVariableStatement(stmt)) continue;
    const isExported = stmt.modifiers?.some((m) => m.kind === ts.SyntaxKind.ExportKeyword);
    if (!isExported) continue;
    for (const decl of stmt.declarationList.declarations) {
      const isMeta = ts.isIdentifier(decl.name) && decl.name.text.endsWith(META_SUFFIX);
      if (isMeta && decl.initializer && ts.isObjectLiteralExpression(decl.initializer)) {
        found.push(decl);
      }
    }
  }
  if (found.length !== 1) {
    throw new Error(
      `${sf.fileName}:1: expected exactly one exported <name>Meta, found ${found.length}`,
    );
  }
  return found[0];
}

function readEntry(file, category) {
  const decl = findMetaDeclaration(parse(file));
  const obj = decl.initializer;
  const fields = Object.fromEntries(
    LITERAL_FIELDS.map((name) => [name, literalValue(getProp(obj, name), name)]),
  );
  if (fields.category !== category) {
    fail(obj, `category '${fields.category}' does not match folder '${category}'`);
  }
  const solutionsNode = getProp(obj, 'solutions');
  if (!ts.isArrayLiteralExpression(solutionsNode)) {
    fail(solutionsNode, "'solutions' must be an array");
  }
  const solutions = solutionsNode.elements.map(readSolution);
  return {
    ...fields,
    tags: stringArray(getProp(obj, 'tags'), 'tags'),
    hasVisualization: solutions.some((s) => !s.isStub),
    variants: solutions.map(({ variant, label }) => ({ variant, label })),
    importPath: `../../algorithms/${category}/${basename(file, '.ts')}`,
    metaName: decl.name.text,
  };
}

function readCategoryOrder() {
  const sf = parse(MODEL_FILE);
  for (const stmt of sf.statements) {
    if (!ts.isVariableStatement(stmt)) continue;
    for (const decl of stmt.declarationList.declarations) {
      if (ts.isIdentifier(decl.name) && decl.name.text === CATEGORY_LABELS_NAME) {
        return decl.initializer.properties.map(propertyName);
      }
    }
  }
  throw new Error(`${MODEL_FILE}: ${CATEGORY_LABELS_NAME} not found`);
}

function listStepsFiles(category) {
  const dir = join(ALGORITHMS_DIR, category);
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((name) => name.endsWith(STEPS_SUFFIX))
    .sort()
    .map((name) => join(dir, name));
}

function collectEntries(categories) {
  const entries = categories.flatMap((category, order) =>
    listStepsFiles(category).map((file) => ({ ...readEntry(file, category), order })),
  );
  return entries.sort((a, b) => a.order - b.order || a.lcNumber - b.lcNumber);
}

function emitEntry(e) {
  const load = `once(() => import(${JSON.stringify(e.importPath)}).then((m) => m.${e.metaName}))`;
  return `{
    id: ${JSON.stringify(e.id)},
    lcNumber: ${e.lcNumber},
    title: ${JSON.stringify(e.title)},
    difficulty: ${JSON.stringify(e.difficulty)},
    category: ${JSON.stringify(e.category)},
    tags: ${JSON.stringify(e.tags)},
    hint: ${JSON.stringify(e.hint)},
    hasVisualization: ${e.hasVisualization},
    variants: ${JSON.stringify(e.variants)},
    load: ${load},
  }`;
}

async function render(entries) {
  const body = entries.map(emitEntry).join(',\n  ');
  const source = `${HEADER}\n${PREAMBLE}\nexport const ALGORITHM_INDEX: readonly AlgorithmIndexEntry[] = [\n  ${body},\n];\n${POSTAMBLE}`;
  const options = (await prettier.resolveConfig(OUTPUT_FILE)) ?? {};
  return prettier.format(source, { ...options, filepath: OUTPUT_FILE });
}

function normalizeEol(text) {
  return text.replace(/\r\n/g, '\n');
}

function summarize(entries) {
  const stubs = entries.filter((e) => !e.hasVisualization).length;
  return `${entries.length} entries, ${stubs} without visualization`;
}

/** Every problem's parsed index entry (lcNumber, title, hasVisualization, ...), in registry order. */
export function readAlgorithmEntries() {
  return collectEntries(readCategoryOrder());
}

async function main() {
  const entries = readAlgorithmEntries();
  const output = await render(entries);
  if (!process.argv.includes(CHECK_FLAG)) {
    writeFileSync(OUTPUT_FILE, output, 'utf8');
    console.log(`gen-registry: wrote ${OUTPUT_FILE} (${summarize(entries)})`);
    return;
  }
  const current = existsSync(OUTPUT_FILE) ? normalizeEol(readFileSync(OUTPUT_FILE, 'utf8')) : null;
  if (current === output) {
    console.log(`gen-registry: up to date (${summarize(entries)})`);
    return;
  }
  console.error('gen-registry: algorithms.index.ts is stale — run `npm run gen:registry`.');
  process.exitCode = 1;
}

const isCli = process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href;
if (isCli) {
  main().catch((err) => {
    console.error(`gen-registry: ${err.message}`);
    process.exitCode = 1;
  });
}
